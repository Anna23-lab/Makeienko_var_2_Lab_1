x1 = float(input())
y1 = float(input())
x2 = float(input())
y2 = float(input())
x3 = float(input())
y3 = float(input())
x4 = float(input())
y4 = float(input())
s = abs((x2 - x1) * (y4 - y1) - (x4 - x1) * (y2 - y1))   # Площа = модуль векторного добутку сторін (вершина 1 -> 2 та 1 -> 4)
d1 = ((x3 - x1)**2 + (y3 - y1)**2)**0.5   # Довжина діагоналі 1 -> 3 (відстань між двома точками)
d2 = ((x4 - x2)**2 + (y4 - y2)**2)**0.5   # Довжина діагоналі 2 -> 4 (відстань між двома точками)
print("Area:", round(s, 3))
print("First diagonal:", round(d1, 3))
print("Second diagonal:", round(d2, 3))
